"""Generate street_steam_emitters.h: which native meshes are NYC steam funnels and where the steam leaves them.

Same fingerprint as chimney_smoke/build_emitters.py: a static WoS mesh is
dequantized with gDecompPosScale/Bias = the MODEL bbox/offset, so those six
floats identify the model at every draw. The vents are the top centre of the
funnel tube in model space.

    python build_emitters.py        (needs the meshes in extracted/, see README_RU.md)
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(GAME, "WoS_Arena", "tools"))
import wrapmesh  # noqa: E402

EXTRACTED = os.path.join(HERE, "extracted")
# (name, file, vent in model space): the intact funnel is 4 m tall; the breakable
# version is drawn in pieces, phys000 is the 1.4 m tube centred on its origin.
SOURCES = [
    ("s_steamfunnel000", "E17.0xB818D824.s_steamfunnel000.wrap.mesh", None),
    ("s_steamfunnel_phys000", "E17.0xDF6D2E87.s_steamfunnel_phys000.wrap.mesh", None),
]


def lit(x):
    t = "%.9g" % x
    if "." not in t and "e" not in t:
        t += ".0"
    return t + "f"


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def main():
    rows, seen = [], {}
    for name, file, vent in SOURCES:
        m = wrapmesh.parse(open(os.path.join(EXTRACTED, file), "rb").read())
        box = tuple(f32(v) for v in (*m.model["bbox"][:3], *m.model["offset"][:3]))
        if box in seen:
            raise SystemExit(f"{name} has the same model box as {seen[box]}")
        seen[box] = name
        if vent is None:  # top centre of the model box
            vent = (box[3], box[4] + abs(box[1]), box[5])
        rows.append((name, box, vent))
    out = ["#pragma once",
           "// Generated by build_emitters.py -- do not edit by hand.",
           "// scale = model bbox, bias = model offset (the native gDecompPosScale/Bias);",
           "// vent = where the steam leaves the funnel, model space.",
           "namespace WosStreetSteam {",
           "struct Model { const char* name; float scale[3], bias[3], vent[3]; };",
           "static const Model kModels[] = {"]
    for name, box, vent in rows:
        out.append('    {"%s", {%s, %s, %s}, {%s, %s, %s}, {%s, %s, %s}},'
                   % (name, *(lit(v) for v in box), *(lit(v) for v in vent)))
    out += ["};", "} // namespace WosStreetSteam", ""]
    path = os.path.join(HERE, "street_steam_emitters.h")
    open(path, "w", newline="\n").write("\n".join(out))
    print(f"{len(rows)} models -> {path}")


if __name__ == "__main__":
    main()
