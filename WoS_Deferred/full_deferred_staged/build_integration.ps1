$ErrorActionPreference = 'Stop'
$stageDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$sourceDir = Join-Path $stageDir 'integration'
$projectDir = Join-Path (Split-Path -Parent (Split-Path -Parent $stageDir)) 'WoS_VolumetricClouds'
$imguiDir = Join-Path $projectDir 'tools\imgui'
$buildDir = Join-Path $stageDir 'build'
$vcvars = 'C:\Program Files\Microsoft Visual Studio\18\Community\VC\Auxiliary\Build\vcvars32.bat'
$dumpbin = 'C:\Program Files\Microsoft Visual Studio\18\Community\VC\Tools\MSVC\14.51.36231\bin\Hostx64\x86\dumpbin.exe'
$systemWinmm = 'C:\Windows\SysWOW64\winmm.dll'
New-Item -ItemType Directory -Force -Path $buildDir | Out-Null

# Export the complete 32-bit WinMM API through jump thunks into the system DLL,
# loaded by full path on first use (winmm_forward.h); no renamed copy of
# Windows' winmm.dll has to sit next to the game. The two timer exports stay
# hand-written C functions.
$generatedDef = Join-Path $buildDir 'winmm.generated.def'
$generatedForward = Join-Path $buildDir 'winmm_forward.h'
$defLines = [System.Collections.Generic.List[string]]::new()
$defLines.Add('LIBRARY winmm')
$defLines.Add('EXPORTS')
$fwdNames = [System.Collections.Generic.List[string]]::new()
$fwdThunks = [System.Collections.Generic.List[string]]::new()
$exportDump = & $dumpbin /exports $systemWinmm
foreach ($line in $exportDump) {
    if ($line -match '^\s+(\d+)\s+[0-9A-F]+\s+[0-9A-F]+\s+(\S+)\s*$') {
        $ordinal = $Matches[1]
        $name = $Matches[2]
        if ($name -eq '[NONAME]') { continue }
        if ($name -eq 'timeSetEvent') {
            $defLines.Add('    timeSetEvent=_proxy_timeSetEvent@20 @' + $ordinal)
        } elseif ($name -eq 'timeKillEvent') {
            $defLines.Add('    timeKillEvent=_proxy_timeKillEvent@4 @' + $ordinal)
        } else {
            $index = $fwdNames.Count
            $fwdNames.Add('    "' + $name + '",')
            $fwdThunks.Add('extern "C" __declspec(naked) void wos_fwd_' + $index + '() { __asm { mov eax, dword ptr [g_wos_fwd + ' + (4 * $index) + '] } __asm { test eax, eax } __asm { jz slow } __asm { jmp eax } slow: __asm { push ' + $index + ' } __asm { jmp WosFwdCommon } }')
            $defLines.Add('    ' + $name + '=wos_fwd_' + $index + ' @' + $ordinal)
        }
    }
}
if ($fwdNames.Count -lt 150) { throw 'Unexpected WinMM export list' }
$defLines | Set-Content -LiteralPath $generatedDef -Encoding Ascii
$forward = [System.Collections.Generic.List[string]]::new()
$forward.Add('// Generated by build_integration.ps1 from the system WinMM export table.')
$forward.Add('#pragma once')
$forward.Add('static const char *const kWosFwdNames[] = {')
$forward.AddRange($fwdNames)
$forward.Add('};')
$forward.Add('static void *g_wos_fwd[' + $fwdNames.Count + '] = {};')
$forward.Add('extern "C" void *__cdecl WosFwdResolve(unsigned index) { return WosForwardResolve(index, kWosFwdNames, g_wos_fwd); }')
$forward.Add('// Saves every register, resolves the target, then jumps there with the caller''s stack untouched.')
$forward.Add('extern "C" __declspec(naked) void WosFwdCommon() { __asm { pushad } __asm { push dword ptr [esp + 32] } __asm { call WosFwdResolve } __asm { add esp, 4 } __asm { mov dword ptr [esp + 28], eax } __asm { popad } __asm { add esp, 4 } __asm { jmp eax } }')
$forward.AddRange($fwdThunks)
$forward | Set-Content -LiteralPath $generatedForward -Encoding Ascii

$sources = @(
    (Join-Path $sourceDir 'wos_clouds_menu.cpp'),
    (Join-Path $imguiDir 'imgui.cpp'),
    (Join-Path $imguiDir 'imgui_draw.cpp'),
    (Join-Path $imguiDir 'imgui_tables.cpp'),
    (Join-Path $imguiDir 'imgui_widgets.cpp'),
    (Join-Path $imguiDir 'backends\imgui_impl_win32.cpp'),
    (Join-Path $imguiDir 'backends\imgui_impl_dx9.cpp')
) | ForEach-Object { '"' + $_ + '"' }

$vsInstaller = 'C:\Program Files (x86)\Microsoft Visual Studio\Installer'
# DLAA (dlss_runtime.h) talks to DXVK's VkDevice: Khronos headers only, no Vulkan import library.
$vulkanHeaders = Join-Path (Split-Path -Parent $projectDir) 'WoS_Research\external\vulkan_headers_1.4.363.0\include'
$command = 'set "PATH=' + $vsInstaller + ';%PATH%" && call "' + $vcvars + '" && cd /d "' + $buildDir + '" && cl /nologo /LD /MT /EHsc /std:c++17 /utf-8 /O2 /I"' + $imguiDir + '" /I"' + (Join-Path $imguiDir 'backends') + '" /I"' + $vulkanHeaders + '" ' + ($sources -join ' ') + ' /link /DEF:"' + $generatedDef + '" /OUT:winmm.dll d3d9.lib user32.lib winmm.lib dxguid.lib'
python (Join-Path $stageDir 'freeze_build.py') begin
if ($LASTEXITCODE -ne 0) { throw 'Build input freeze failed' }
cmd.exe /c $command
if ($LASTEXITCODE -ne 0) { throw 'Cloud menu build failed' }
python (Join-Path $stageDir 'freeze_build.py') finish
if ($LASTEXITCODE -ne 0) { throw 'Build verification failed' }
Write-Host (Join-Path $buildDir 'winmm.dll')
