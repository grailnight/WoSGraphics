"""
Extract the two reflection cube maps for the night reflection swap.

WoS ships both cubes Spider-Man 3 uses for window/car reflections:
  cubemapfromlod        (0x812D2DD0, GAME pack)      - day city, bound to ReflectionSampler
  cubemapfromlod_night  (0x5C883CC9, MEGACITY pack)  - night city, byte-identical to SM3's,
                                                       never referenced by the WoS exe
Both are 128x128 DXT1 cubes with 8 mips; the .wrap.tex PHYS is six mip chains
back to back in D3D face order (+X -X +Y -Y +Z -Z) at the end of the file.

Writes next to this script:
  cubemapfromlod_night.bin   raw PHYS (6 chains, 65616 bytes), loaded by the DLL
  day_signature.h            first bytes of each day face, used to recognise the
                             engine's day cube at SetTexture time

Run under py -3.10 (wospack's bundled lzo).
"""

import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.abspath(os.path.join(HERE, "..", ".."))
TOOLS = os.path.join(GAME, "WoS_VolumetricClouds", "tools", "WebOfShadowsTools", "python")
OUT_TMP = os.path.join(HERE, "extracted")

WIDTH, MIPS, BLOCK = 128, 8, 8
SIGNATURE_BYTES = 32
SOURCES = {
    "day": ("GAME", "_0x003A261A.Game.pcapk", "0x812D2DD0.cubemapfromlod.wrap.tex"),
    "night": ("MEGACITY", "_0xEE185533.megacity.pcapk", "0x5C883CC9.cubemapfromlod_night.wrap.tex"),
}


def chain_size():
    total, w = 0, WIDTH
    for _ in range(MIPS):
        total += max(1, w // 4) ** 2 * BLOCK
        w = max(1, w // 2)
    return total


CHAIN = chain_size()          # 10936
PHYS = 6 * CHAIN              # 65616


def unpack(pack):
    sys.path.insert(0, os.path.join(GAME, "WoS_Arena", "tools"))
    from wospack import lzo_import
    lzo_import()                  # puts the bundled lzo on sys.path
    sys.path.insert(0, TOOLS)
    from wos import cli
    sys.argv = ["unpack_wos", os.path.join(GAME, "packs", pack + ".PCPACK"), OUT_TMP, "-e", "-apk", "-q"]
    cli.main()


def phys(key):
    pack, apk, name = SOURCES[key]
    path = os.path.join(OUT_TMP, pack, apk, name)
    if not os.path.exists(path):
        unpack(pack)
    d = open(path, "rb").read()
    hdr = d.find(b"DXT1")
    w, h, depth, mips = struct.unpack_from("<4I", d, hdr - 0x10)
    if (w, h, depth, mips) != (WIDTH, WIDTH, 6, MIPS):
        raise SystemExit(f"{name}: unexpected header {w}x{h} depth {depth} mips {mips}")
    print(f"{name}: {len(d)} bytes, PHYS {PHYS}")
    return d[-PHYS:]


def main():
    open(os.path.join(HERE, "cubemapfromlod_night.bin"), "wb").write(phys("night"))
    day = phys("day")
    lines = [
        "#pragma once",
        "// Generated by extract_cubes.py: the first bytes of mip 0 of every face of",
        "// the engine's day reflection cube (cubemapfromlod, 128x128 DXT1, 8 mips).",
        "namespace WosNightReflection {",
        f"static const unsigned kSignatureBytes = {SIGNATURE_BYTES};",
        "static const unsigned char kDaySignature[6][kSignatureBytes] = {",
    ]
    for f in range(6):
        b = day[f * CHAIN: f * CHAIN + SIGNATURE_BYTES]
        lines.append("    { " + ", ".join(f"0x{x:02X}" for x in b) + " },")
    lines += ["};", "} // namespace WosNightReflection", ""]
    open(os.path.join(HERE, "day_signature.h"), "w", newline="\n").write("\n".join(lines))
    print("wrote cubemapfromlod_night.bin and day_signature.h")


if __name__ == "__main__":
    main()
