"""Bake axisymmetric sky convolution and GGX split-sum BRDF. No game writes."""
from pathlib import Path
import json, hashlib
import numpy as np
ROOT=Path(__file__).resolve().parent
W,R,D,N=128,32,64,1024
def smooth(a,b,x):
    t=np.clip((x-a)/(b-a),0,1); return t*t*(3-2*t)
def basis(y,profile):
    h=np.clip(y,0,1)
    if profile:
        a=smooth(0,.28,h); b=smooth(.18,.9,h)
        weights=np.stack(((1-a)*(1-b),a*(1-b),b),-1)
    else:
        a=h**.55; b=smooth(0,.055,h)
        weights=np.stack(((1-a)*b,1-b,a*b),-1)
    # RGB-dependent extinction requires one basis triplet per colour channel.
    # Bake each wavelength separately, returned as [sample, source, RGB].
    transmission=np.exp(-np.array([.09,.165,.335])/np.sqrt(h[...,None]**2+.025))
    atmosphere=np.stack((1-transmission,np.zeros_like(transmission),transmission),-2)
    blend=.55*smooth(0,.075,h)
    result=weights[...,None]*(1-blend[...,None,None])+atmosphere*blend[...,None,None]
    return result*(y>0)[...,None,None]
def sequence(n):
    i=np.arange(n,dtype=np.uint32); v=i.copy(); out=np.zeros(n)
    for bit in range(32): out+=((v>>bit)&1)*2.**(-bit-1)
    return (i+.5)/n,out
def main():
    u,q=sequence(N); phi=2*np.pi*u
    elevations=np.linspace(-1,1,W)
    # Store three textures, one per source colour, RGB are wavelength weights.
    maps=np.zeros((3,R+1,W*2,4),np.float32)
    for profile in (False,True):
        offset=int(profile)*W
        for row in range(R):
            rough=.02+.98*row/(R-1); a=rough*rough
            hz=np.sqrt((1-q)/(1+(a*a-1)*q)); hr=np.sqrt(1-hz*hz)
            # V=N. Reflect V around sampled GGX H. Normalize by sum(NoL).
            lz=2*hz*hz-1; lx=2*hz*hr*np.cos(phi)
            weight=np.maximum(lz,0); denom=weight.sum()
            y=elevations[:,None]*lz+np.sqrt(np.maximum(1-elevations**2,0))[:,None]*lx
            value=(basis(y,profile)*weight[None,:,None,None]).sum(1)/denom
            for source in range(3): maps[source,row,offset:offset+W,:3]=value[:,source,:]
        # Cosine-weighted hemisphere integral: mean(L) equals irradiance/pi.
        lz=np.sqrt(1-q); lx=np.sqrt(q)*np.cos(phi)
        y=elevations[:,None]*lz+np.sqrt(np.maximum(1-elevations**2,0))[:,None]*lx
        value=basis(y,profile).mean(1)
        for source in range(3): maps[source,R,offset:offset+W,:3]=value[:,source,:]
    # Smith-correlated GGX integrated BRDF, F = F0*(1-Fc) + F90*Fc.
    brdf=np.zeros((D,D,4),np.float32)
    for row in range(D):
        rough=.02+.98*row/(D-1); a2=rough**4
        hz=np.sqrt((1-q)/(1+(a2-1)*q)); hr=np.sqrt(1-hz*hz)
        hx=hr*np.cos(phi); hy=hr*np.sin(phi)
        for col in range(D):
            nv=max(col/(D-1),1e-4); vx=np.sqrt(1-nv*nv)
            vh=np.maximum(vx*hx+nv*hz,0); nl=2*vh*hz-nv
            valid=nl>0; nl=np.maximum(nl,0)
            visibility=.5/np.maximum(nl*np.sqrt(a2+(1-a2)*nv*nv)+nv*np.sqrt(a2+(1-a2)*nl*nl),1e-10)
            weight=4*visibility*nl*vh/np.maximum(hz,1e-8)*valid
            fc=(1-vh)**5
            brdf[row,col,:2]=[np.mean(weight*(1-fc)),np.mean(weight*fc)]
    assert np.isfinite(maps).all() and np.min(maps)>=0
    assert np.isfinite(brdf).all() and np.min(brdf)>=0
    assert np.max(brdf[:,:,:2].sum(-1))<1.015
    # Independent hemisphere-energy sanity: RGB source weights sum to sky visibility.
    sums=maps[:,:,:,:3].sum(0)
    assert np.max(np.abs(sums[R,W-1]-1))<.002
    assert np.max(sums[R,0])<.002
    arrays={**{f'sky_weights_{i}':maps[i].astype('<f2') for i in range(3)},'sky_brdf':brdf.astype('<f2')}
    lines=['#pragma once','// Generated by bake.py; IEEE half floats, RGBA.','namespace WosSkyIBLData {']
    for name,values in arrays.items():
        (ROOT/(name+'.bin')).write_bytes(values.tobytes())
        bits=values.view(np.uint16).ravel()
        lines.append(f'static const unsigned short {name}[]={{')
        lines.extend(','.join(map(str,bits[i:i+24]))+',' for i in range(0,len(bits),24))
        lines.append('};')
    lines.append('}')
    (ROOT/'sky_lut.generated.h').write_text('\n'.join(lines))
    receipt={'samples':N,'weights_size':[W*2,R+1],'brdf_size':[D,D],'sky_blend':.55,
             'brdf_max_energy':float(brdf[:,:,:2].sum(-1).max()),
             'sha256':{name:hashlib.sha256((ROOT/(name+'.bin')).read_bytes()).hexdigest() for name in arrays}}
    (ROOT/'bake.json').write_text(json.dumps(receipt,indent=2));print(json.dumps(receipt))
if __name__=='__main__':main()
