"""Generate lamp_models.h: NYC street lamp meshes and where their bulbs are.

Same fingerprint as chimney_smoke/build_emitters.py: every city vertex shader
receives the model box (gDecompPosScale = bbox half extents, gDecompPosBias =
offset), so the six floats identify the lamp model at draw time. Bulbs were
measured from the decoded lamp-head submesh (glass/bulb material) in model space.

    python build_lamps.py
"""
import glob
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(GAME, "WoS_Arena", "tools"))
import wrapmesh  # noqa: E402

MEGACITY = os.path.join(GAME, "WoS_VolumetricClouds", "extracted", "MEGACITY", "MEGACITY", "_0xEE185533.megacity.pcapk")

# kind: 0 tall cobra-head street light, 1 double-head lamp, 2 park lamp
# bulbs: (x, y, z) in model space, just under the lamp glass
COBRA = [(0.0, 10.10, 3.53)]
DOUBLE = [(0.0, 3.90, 0.55), (0.0, 3.90, -0.55)]
PARK = [(0.0, 3.80, 0.0)]
SOURCES = [
    ("s_str_light_ssingle000", 0, COBRA),
    ("s_str_light_ssingle002", 0, COBRA),
    ("s_str_light_fdouble000", 1, DOUBLE),
    ("s_str_light_fdouble001", 1, DOUBLE),
    ("s_str_light_fdouble002", 1, DOUBLE),
    ("s_str_light_fdouble003", 1, DOUBLE),
    ("s_park_light1a000", 2, PARK),
    ("s_park_light1a001", 2, PARK),
    ("s_park_light1a003", 2, PARK),
]
# ssingle001 shares ssingle000's box, park_light1a002 shares 1a001's box.
# The bent *_dam models are knocked-over lamps and stay dark.


def lit(x):
    t = "%.9g" % x
    if "." not in t and "e" not in t:
        t += ".0"
    return t + "f"


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def main():
    rows, seen = [], {}
    for name, kind, bulbs in SOURCES:
        hits = glob.glob(os.path.join(MEGACITY, "*." + name + ".wrap.mesh"))
        if len(hits) != 1:
            raise SystemExit(f"{name}: {len(hits)} mesh files")
        m = wrapmesh.parse(open(hits[0], "rb").read())
        box = tuple(f32(v) for v in (*m.model["bbox"][:3], *m.model["offset"][:3]))
        if box in seen:
            raise SystemExit(f"{name} has the same model box as {seen[box]}")
        seen[box] = name
        for b in bulbs:
            for axis, v in enumerate(b):
                lo, hi = box[3 + axis] - abs(box[axis]), box[3 + axis] + abs(box[axis])
                if not lo - 0.3 <= v <= hi + 0.3:
                    raise SystemExit(f"{name}: bulb outside the model box on axis {axis}")
        rows.append((name, box, kind, bulbs))
    out = ["#pragma once",
           "// Generated by build_lamps.py -- do not edit by hand.",
           "// scale = model bbox, bias = model offset (gDecompPosScale/Bias). Bulbs are model space.",
           "namespace WosNightLamps {",
           "struct Bulb { float x, y, z; };",
           "struct LampModel { const char* name; float scale[3], bias[3]; int kind; unsigned bulbs; Bulb bulb[2]; };",
           "static const LampModel kLampModels[] = {"]
    for name, box, kind, bulbs in rows:
        bl = ", ".join("{%.4ff, %.4ff, %.4ff}" % b for b in bulbs)
        if len(bulbs) == 1:
            bl += ", {0, 0, 0}"
        out.append('    {"%s", {%s, %s, %s}, {%s, %s, %s}, %d, %d, {%s}},'
                   % (name, *(lit(v) for v in box), kind, len(bulbs), bl))
    out += ["};", "} // namespace WosNightLamps", ""]
    path = os.path.join(HERE, "lamp_models.h")
    open(path, "w", newline="\n").write("\n".join(out))
    print(f"{len(rows)} models -> {path}")


if __name__ == "__main__":
    main()
