"""Generate chimney_emitters.h: which native meshes are chimneys and where their flues are.

A static WoS mesh stores SHORT4N positions quantized over its MODEL box, and
every city vertex shader dequantizes them with gDecompPosScale/gDecompPosBias,
which are exactly the model's bbox (half extents) and offset (centre). Those six
floats are therefore a fingerprint of the model that is already on the GPU at
every draw, so the renderer can recognise a chimney without locking a texture
or a vertex buffer. The flue points below were measured from the decoded
geometry (highest vertex clusters) and are in the same model space.

    python build_emitters.py        (needs the extracted meshes listed in SOURCES)
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(GAME, "WoS_Arena", "tools"))
import wrapmesh  # noqa: E402

MEGACITY = os.path.join(GAME, "WoS_VolumetricClouds", "extracted", "MEGACITY", "MEGACITY", "_0xEE185533.megacity.pcapk")
CELL = os.path.join(HERE, "extracted", "G14", "_0x0001BCAC.G14.pcapk")

# kind: 0 house chimney, 1 industrial smokestack
# flues: (x, y, z, radius) in model space
SOURCES = [
    ("s_rf_chimneya000", MEGACITY, "0xDE429E47.s_rf_chimneya000.wrap.mesh", 0, [(-0.10, 5.62, -0.21, 0.45)]),
    ("s_rf_chimneya001", MEGACITY, "0xDE429E48.s_rf_chimneya001.wrap.mesh", 0, [(-0.10, 5.50, -0.20, 0.45)]),
    ("s_rf_chimneyb000", CELL, "0xDE432AA8.s_rf_chimneyb000.wrap.mesh", 0, [(0.23, 5.60, -0.68, 0.45), (-0.51, 5.08, 0.36, 0.30)]),
    ("s_rf_chimneyb001", CELL, "0xDE432AA9.s_rf_chimneyb001.wrap.mesh", 0, [(0.23, 5.50, -0.60, 0.45), (-0.43, 5.00, 0.60, 0.30)]),
    ("s_rf_chimneyc000", MEGACITY, "0xDE43B709.s_rf_chimneyc000.wrap.mesh", 0, [(0.0, 3.00, 0.0, 0.28)]),
    ("s_rf_chimneyc001", MEGACITY, "0xDE43B70A.s_rf_chimneyc001.wrap.mesh", 0, [(0.0, 3.00, 0.0, 0.28)]),
    ("s_rf_smokestacka001", CELL, "0x1A0AB6B0.s_rf_smokestacka001.wrap.mesh", 1, [(0.0, 104.0, 0.0, 3.4)]),
    ("s_rf_smokestacka002", CELL, "0x1A0AB6B1.s_rf_smokestacka002.wrap.mesh", 1, [(0.0, 104.0, 0.0, 3.4)]),
    ("s_rf_smokestacka003", CELL, "0x1A0AB6B2.s_rf_smokestacka003.wrap.mesh", 1, [(0.0, 104.0, 0.0, 3.4)]),
]
# LOD002 of chimneya/b shares its model box with LOD001, so one row covers both.


def lit(x):
    t = "%.9g" % x
    if "." not in t and "e" not in t:
        t += ".0"
    return t + "f"


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def main():
    rows, seen = [], {}
    for name, folder, file, kind, flues in SOURCES:
        m = wrapmesh.parse(open(os.path.join(folder, file), "rb").read())
        box = tuple(f32(v) for v in (*m.model["bbox"][:3], *m.model["offset"][:3]))
        if box in seen:
            raise SystemExit(f"{name} has the same model box as {seen[box]}")
        seen[box] = name
        for fx, fy, fz, r in flues:
            for axis, v in enumerate((fx, fy, fz)):
                lo, hi = box[3 + axis] - abs(box[axis]), box[3 + axis] + abs(box[axis])
                if not lo - 0.5 <= v <= hi + 0.5:
                    raise SystemExit(f"{name}: flue outside the model box on axis {axis}")
        rows.append((name, box, kind, flues))
    out = ["#pragma once",
           "// Generated by build_emitters.py -- do not edit by hand.",
           "// scale = model bbox, bias = model offset: the gDecompPosScale/Bias the",
           "// native vertex shader receives for this model. Flues are model space.",
           "namespace WosChimneySmoke {",
           "struct Flue { float x, y, z, radius; };",
           "struct Model { const char* name; float scale[3], bias[3]; int kind; unsigned flues; Flue flue[2]; };",
           "static const Model kModels[] = {"]
    for name, box, kind, flues in rows:
        fl = ", ".join("{%.4ff, %.4ff, %.4ff, %.3ff}" % f for f in flues)
        if len(flues) == 1:
            fl += ", {0, 0, 0, 0}"
        out.append('    {"%s", {%s, %s, %s}, {%s, %s, %s}, %d, %d, {%s}},'
                   % (name, *(lit(v) for v in box), kind, len(flues), fl))
    out += ["};", "} // namespace WosChimneySmoke", ""]
    path = os.path.join(HERE, "chimney_emitters.h")
    open(path, "w", newline="\n").write("\n".join(out))
    print(f"{len(rows)} models -> {path}")


if __name__ == "__main__":
    main()
