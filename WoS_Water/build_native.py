"""Build exact-byte native water replacements, preserving engine CTAB bindings."""
from pathlib import Path
import sys, re, json, hashlib, ctypes as C
ROOT=Path(__file__).resolve().parent
sys.path.insert(0,str(ROOT.parent/'WoS_Research/native_engine'))
import ast
module=ast.parse((ROOT.parent/'WoS_Research/native_engine/roundtrip_original_shaders.py').read_text())
selected=[n for n in module.body if isinstance(n,(ast.Import,ast.ImportFrom,ast.FunctionDef))]
# Import only pure helper definitions, never the other script's top-level build.
exec(compile(ast.Module(body=selected,type_ignores=[]),'<shader helpers>','exec'))
api=C.WinDLL('d3dx9_43.dll')
assemble=api.D3DXAssembleShader
assemble.argtypes=[C.c_char_p,C.c_uint,C.c_void_p,C.c_void_p,C.c_uint,C.POINTER(C.c_void_p),C.POINTER(C.c_void_p)]
assemble.restype=C.c_long

def change(source, old, new):
    assert source.count(old)==1, (old, source.count(old))
    return source.replace(old,new)

records=[]
header=['#pragma once', '// Generated by WoS_Water/build_native.py. Exact original programs only.', 'namespace WosWaterAssets {']
for index,name in enumerate(('sm_water_mesh','sm_water_pond_mesh','sm_water_pond_uv1')):
    raw=(ROOT/'native'/f'{name}.component0.ps.cso').read_bytes()
    source=(ROOT/'native'/f'{name}.component0.ps.asm').read_text()
    if index==0:
        source=change(source,'def c20, 4, 20, 0, 0','def c20, 4, 20, 5, 0')
        source=change(source,'def c21, 0.610000014, 0.639999986, 0.600000024, 0','def c21, 0.65, 0.70, 0.72, 0')
        source=change(source,'def c22, -0.0483999997, -0.057599999, -0.0324000008, 0','def c22, -0.018, -0.030, -0.035, 0\n    def c23, 0.004, 0.004, 0.4, 0.15\n    def c24, 0.75, 0, 0, 0')
        source=change(source,'mul r0.x, r0.x, r0.y','pow r0.x, r0.x, c20.z')
        # Keep the three independently scrolling native normal layers. No sine grid.
        source=change(source,'mul r2.xy, r2, r1.w','mul r2.xy, r2, r1.w\n    mul r2.xy, r2, c24.x')
        # Five taps soften the native environment map's hard mirrored detail.
        source=change(source,'texld r2, r0.yzzw, s0',
                      'texld r2, r0.yzzw, s0\n    mov r20.xy, r0.yzzw\n    add r20.x, r20.x, c23.x\n    texld r21, r20, s0\n    mov r20.xy, r0.yzzw\n    add r20.x, r20.x, -c23.x\n    texld r22, r20, s0\n    mov r20.xy, r0.yzzw\n    add_sat r20.y, r20.y, c23.y\n    texld r23, r20, s0\n    mov r20.xy, r0.yzzw\n    add_sat r20.y, r20.y, -c23.y\n    texld r24, r20, s0\n    add r21, r21, r22\n    add r23, r23, r24\n    add r21, r21, r23\n    mul r2, r2, c23.z\n    mad r2, r21, c23.w, r2')

    elif index==1:
        source=change(source,'def c66, 1000, 0.600000024, 0.00100000005, 0.00999999978',
                      'def c66, 192, 0.600000024, 0.00100000005, 0.00999999978\n    def c67, 3, 0.18, 0.02037, 0.97963')
        # Exact native alpha uses Fresnel too; save the original in r21.x.
        source=change(source,'mad r1.w, r3.w, r1.w, r2.w',
                      'mad r1.w, r3.w, r1.w, r2.w\n    mov r21.x, r1.w\n    pow r3.w, r2.x, c63.w\n    mad r1.w, r3.w, c67.w, c67.z')
        source=change(source,'min r2.x, r0.x, r1.w','min r2.x, r0.x, r21.x')
        # Two native scrolling normal layers form crossing light bands.
        source=change(source,'texld r4, r4, s5',
                      'texld r4, r4, s5\n    add r20.xy, r6, c61.x\n    add r20.zw, r4.xyxy, c61.x\n    add r20.xy, r20, r20.zwzw\n    abs r20.xy, r20\n    add r20.x, r20.x, r20.y\n    mov r20.y, c62.y\n    mad_sat r20.x, r20.x, -c67.x, r20.y\n    mul r20.x, r20.x, r20.x\n    mul r20.x, r20.x, r20.x')
        # r2.x is the original depth/feather ratio. No raw-depth-as-meters claim.
        source=change(source,'add r4.w, -r3.w, c62.y',
                      'add r4.w, -r3.w, c62.y\n    add r20.y, r2.x, c62.y\n    rcp r20.y, r20.y\n    mul r20.x, r20.x, r20.y\n    mul_sat r20.y, r2.x, c67.x\n    mul r20.x, r20.x, r20.y\n    mul r20.x, r20.x, c67.y\n    mad r4.xyz, r4, r20.x, r4')
    else:
        source=change(source,'def c55, 1000, 0.00999999978, 0, 0',
                      'def c55, 192, 0.00999999978, 0, 0\n    def c56, 0.02037, 0.97963, 5, 0')
        # UV1 alpha depends on eta/F0, not r2.x, so keep those instructions.
        # The original 1-NdotV is live in r2.x before the final Fresnel MAD.
        source=change(source,'pow r5.z, r2.x, r2.y','pow r5.z, r2.x, c56.z')
        source=change(source,'mad r2.x, r5.z, r2.x, r5.y','mad r2.x, r5.z, c56.y, c56.x')
    # Remove stale compiler instruction count from generated listing.
    source=re.sub(r'// approximately .*','// Native water replacement; see disassembly for actual instruction count.',source)
    code,error=C.c_void_p(),C.c_void_p();encoded=source.encode()
    hr=assemble(encoded,len(encoded),None,None,0,C.byref(code),C.byref(error))
    diagnostics=blob(error).decode(errors='replace') if error else ''
    if hr<0:raise RuntimeError(name+': '+diagnostics)
    executable,_=split(blob(code));_,ctab=split(raw)
    result=executable[:4]+b''.join(ctab)+executable[4:]
    assert split(result)[1]==ctab
    (ROOT/f'{name}.native.asm').write_text(source)
    (ROOT/f'{name}.native.cso').write_bytes(result)
    for prefix,data in [('original',raw),('replacement',result)]:
        header.append(f'static const unsigned char {prefix}{index}[] = {{')
        header += [','.join(str(x) for x in data[k:k+32])+',' for k in range(0,len(data),32)]
        header.append('};')
    records.append(dict(name=name,original_bytes=len(raw),replacement_bytes=len(result),
                        original_sha256=hashlib.sha256(raw).hexdigest(),replacement_sha256=hashlib.sha256(result).hexdigest(),ctab_preserved=True))
header += ['struct Asset { const char* name; const unsigned char* original; unsigned originalSize; const unsigned char* replacement; unsigned replacementSize; };','static const Asset assets[] = {']
for index,r in enumerate(records):
    header.append(f'{{"{r["name"]}",original{index},sizeof(original{index}),replacement{index},sizeof(replacement{index})}},')
header+=['};','}']
(ROOT/'native_assets.h').write_text('\n'.join(header)+'\n')
(ROOT/'native_build.json').write_text(json.dumps(records,indent=2))
print(json.dumps(records,indent=2))
